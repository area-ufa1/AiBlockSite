#!/usr/bin/env bash
# Rebuilds app/src/main/assets/blocklists/adult.txt from StevenBlack's porn-only hosts list (MIT).
set -euo pipefail
SRC="https://raw.githubusercontent.com/StevenBlack/hosts/master/alternates/porn-only/hosts"
OUT="$(cd "$(dirname "$0")/.." && pwd)/app/src/main/assets/blocklists/adult.txt"
MAX=150000

tmp=$(mktemp)
curl -fsSL "$SRC" \
  | awk '$1 == "0.0.0.0" && $2 != "0.0.0.0" { print tolower($2) }' \
  | sed 's/^www\.//' \
  | grep -E '^[a-z0-9.-]+\.[a-z0-9-]+$' \
  | sort -u \
  | grep -vxF -f <(grep -v '^#' "$(dirname "$0")/blocklist-exclude.txt" | sed '/^$/d') > "$tmp"

n=$(wc -l < "$tmp")
if [ "$n" -gt "$MAX" ]; then
  echo "blocklist has $n domains, more than $MAX" >&2
  exit 1
fi
{
  echo "# Source: $SRC"
  echo "# Generated by scripts/update-blocklist.sh; $n domains"
  cat "$tmp"
} > "$OUT"
rm -f "$tmp"
echo "wrote $n domains to $OUT"
